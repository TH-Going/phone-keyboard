param(
    [Parameter(Mandatory = $true)][string]$WebDir,
    [Parameter(Mandatory = $true)][string]$OutFile
)

$ErrorActionPreference = "Stop"

# The phone UI is reused verbatim from code/web (browser assets only). It is
# embedded into the executable so the portable build stays a single file.
$assets = @(
    @{ Symbol = "web_html"; File = "controller.html" },
    @{ Symbol = "web_css";  File = "controller.css" },
    @{ Symbol = "web_js";   File = "controller.js" }
)

$builder = [System.Text.StringBuilder]::new()
[void]$builder.AppendLine("#ifndef WEB_ASSETS_H")
[void]$builder.AppendLine("#define WEB_ASSETS_H")
[void]$builder.AppendLine()
[void]$builder.AppendLine("/* Generated by tools/embed.ps1. Do not edit. */")
[void]$builder.AppendLine()

foreach ($asset in $assets) {
    $path = Join-Path $WebDir $asset.File
    if (-not (Test-Path -LiteralPath $path)) {
        throw "Missing web asset: $path"
    }
    $bytes = [System.IO.File]::ReadAllBytes($path)
    if ($bytes.Length -eq 0) {
        throw "Empty web asset: $path"
    }

    [void]$builder.AppendLine("static const unsigned char $($asset.Symbol)_bytes[] = {")
    for ($offset = 0; $offset -lt $bytes.Length; $offset += 20) {
        $count = [Math]::Min(20, $bytes.Length - $offset)
        $chunk = [System.Array]::CreateInstance([byte], $count)
        [System.Array]::Copy($bytes, $offset, $chunk, 0, $count)
        $line = ($chunk | ForEach-Object { "0x{0:X2}" -f $_ }) -join ","
        [void]$builder.AppendLine("    $line,")
    }
    [void]$builder.AppendLine("};")
    [void]$builder.AppendLine("static const unsigned int $($asset.Symbol)_len = $($bytes.Length);")
    [void]$builder.AppendLine()
}

[void]$builder.AppendLine("#endif /* WEB_ASSETS_H */")

[System.IO.File]::WriteAllText($OutFile, $builder.ToString(), [System.Text.UTF8Encoding]::new($false))
Write-Host "embedded $($assets.Count) web assets -> $OutFile"
